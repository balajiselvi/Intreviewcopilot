const fs = require("fs");
const path = require("path");

const pipeline = JSON.parse(fs.readFileSync(path.join(__dirname, "results", "pipeline_results.json"), "utf-8"));
const adversarial = JSON.parse(fs.readFileSync(path.join(__dirname, "results", "adversarial_results.json"), "utf-8"));

const DIMS = ["technical_accuracy", "production_experience", "business_context", "communication", "architecture_thinking", "leadership"];

function fmt(n) { return Number(n).toFixed(2); }

// --- Per-domain table ---
const domainRows = pipeline.map(r => {
  if (r.error) return { domain: r.domain, error: r.error };
  return {
    domain: r.domain,
    raw: r.raw.judge.overall_score,
    improved: r.improved.judge.overall_score,
    delta: Number((r.improved.judge.overall_score - r.raw.judge.overall_score).toFixed(2)),
    findingCount: r.critic.findings.length
  };
});

const scored = domainRows.filter(r => !r.error);
const avgRaw = scored.reduce((s, r) => s + r.raw, 0) / scored.length;
const avgImproved = scored.reduce((s, r) => s + r.improved, 0) / scored.length;

const sortedByImproved = [...scored].sort((a, b) => b.improved - a.improved);
const strongest = sortedByImproved.slice(0, 3);
const weakest = sortedByImproved.slice(-3).reverse();

// --- Dimension breakdown ---
const dimAvgRaw = {};
DIMS.forEach(d => {
  dimAvgRaw[d] = pipeline.filter(r => r.raw).reduce((s, r) => s + (r.raw.judge[d] || 0), 0) / pipeline.filter(r => r.raw).length;
});

// --- Common failure categories ---
const categoryCounts = {};
let totalFindings = 0;
for (const r of pipeline) {
  if (!r.critic) continue;
  for (const f of r.critic.findings) {
    categoryCounts[f.category] = (categoryCounts[f.category] || 0) + 1;
    totalFindings++;
  }
}
const sortedCategories = Object.entries(categoryCounts).sort((a, b) => b[1] - a[1]);

// --- Adversarial ---
const advScored = adversarial.filter(a => a.judge);
const advAvg = advScored.reduce((s, a) => s + a.judge.overall_score, 0) / advScored.length;
const advPassCount = advScored.filter(a => a.pass).length;

let md = `# Interview Copilot — Production-Grade Evaluation Report

Generated by \`eval/generateReport.js\` from \`eval/results/pipeline_results.json\` and \`eval/results/adversarial_results.json\`.

## Methodology

- **Generator**: live single-pass production endpoint (\`/api/chat\`, model \`gpt-4o-mini\`) — exactly what ships to a real interview session.
- **Technical Critic**: separate LLM call, aggressively checks for technical inaccuracies, missing SAP concepts, weak business justification, missing production examples, missing risk discussion, poor structure, generic wording, interview red flags, plus explicit fabrication/accuracy checks (unverifiable claims, incorrect terminology, assumptions stated as fact, unrealistic examples, fabricated experience, version-specific risk).
- **Answer Improver**: revises using ONLY the Critic's findings. Explicitly forbidden from inventing specific projects, employers, numbers, or timelines to fill gaps — must use honest, hedged, general-pattern language instead.
- **Independent Judge**: scores the improved answer cold, on 6 dimensions (Technical Accuracy, Production Experience, Business Context, Communication, Architecture Thinking, Leadership), instructed to be a harsh, realistic grader where 9-10 is rare.
- **Adversarial testing**: 7 difficult-interviewer behaviors (interruption, incorrect assumption, rapid-fire, multi-part, contradictory follow-up, repeated "why", edge-case scenario), each tested against the raw production Generator (no critic/improve step — this measures live behavior as an interview would actually experience it).

## Headline Numbers

| Metric | Value |
|---|---|
| Domains evaluated | ${pipeline.length} |
| Avg raw (production) score | **${fmt(avgRaw)}/10** |
| Avg after Critic→Improve | **${fmt(avgImproved)}/10** |
| Net lift from Critic→Improve | ${fmt(avgImproved - avgRaw)} |
| Domains scoring ≥9.5/10 (raw) | ${scored.filter(r => r.raw >= 9.5).length}/${scored.length} |
| Domains scoring ≥8.5/10 (raw) | ${scored.filter(r => r.raw >= 8.5).length}/${scored.length} |
| Adversarial avg score | **${fmt(advAvg)}/10** |
| Adversarial scenarios staying ≥9/10 | ${advPassCount}/${advScored.length} |

**Important caveat on the scale**: this Judge is deliberately stricter than the single-dimension judge used in the earlier Phase 4 pass (which reported 8.95/10 average). The two numbers are not on the same scale — this one scores 6 separate professional dimensions including production experience and leadership, with instructions to reserve 9-10 for genuinely rare, senior-level answers. A 7/10 here reflects a stricter bar, not a regression in the underlying product.

## Per-Domain Scores (Raw → Improved)

| Domain | Raw | Improved | Δ | Critic findings |
|---|---|---|---|---|
${domainRows.map(r => r.error
  ? `| ${r.domain} | ERROR: ${r.error} | | | |`
  : `| ${r.domain} | ${fmt(r.raw)} | ${fmt(r.improved)} | ${r.delta >= 0 ? "+" : ""}${r.delta} | ${r.findingCount} |`
).join("\n")}

## Strongest Domains (by improved score)

${strongest.map((r, i) => `${i + 1}. **${r.domain}** — ${fmt(r.improved)}/10`).join("\n")}

## Weakest Domains (by improved score)

${weakest.map((r, i) => `${i + 1}. **${r.domain}** — ${fmt(r.improved)}/10`).join("\n")}

## Dimension Breakdown (raw production answers, avg across all domains)

| Dimension | Avg Score |
|---|---|
${DIMS.map(d => `| ${d.replace(/_/g, " ")} | ${fmt(dimAvgRaw[d])}/10 |`).join("\n")}

**Leadership (${fmt(dimAvgRaw.leadership)}/10) and Architecture Thinking (${fmt(dimAvgRaw.architecture_thinking)}/10) are the weakest dimensions**, well below Technical Accuracy (${fmt(dimAvgRaw.technical_accuracy)}/10). Caveat: several of the 19 Tier-1 domains (HANA, BW, Fiori, IPS, IAS config-style questions) are inherently technical/procedural and don't naturally invite a leadership narrative — scoring every domain against a "leadership" dimension penalizes technical questions for not being behavioral questions. This is a rubric-design tension, not purely a content gap, and forcing leadership framing into every technical answer risks the "less natural, less realistic" outcome that should be rejected on sight.

## Common Failure Categories (across ${pipeline.length} domains, ${totalFindings} total findings)

| Category | Domains affected | % of domains |
|---|---|---|
${sortedCategories.map(([cat, count]) => `| ${cat.replace(/_/g, " ")} | ${count}/${pipeline.length} | ${Math.round(count / pipeline.length * 100)}% |`).join("\n")}

**The three most universal issues (100% of domains)** are missing_sap_concepts, weak_business_justification, and missing_risk_discussion. These are the highest-leverage targets for future prompt work — but note the Improver could barely move the score fixing them (net +${fmt(avgImproved - avgRaw)}), because genuinely fixing "weak business justification" or "lack of production examples" requires real specific detail, and the Improver is deliberately barred from inventing that detail.

## Adversarial Testing Results

| Domain | Behavior | Score | ≥9/10? |
|---|---|---|---|
${adversarial.map(a => a.judge
  ? `| ${a.domain} | ${a.behavior} | ${fmt(a.judge.overall_score)}/10 | ${a.pass ? "✅" : "❌"} |`
  : `| ${a.domain} | ${a.behavior} | ERROR | — |`
).join("\n")}

**${advPassCount}/${advScored.length} adversarial scenarios reached the 9/10 threshold. Average adversarial score (${fmt(advAvg)}/10) is roughly in line with the non-adversarial baseline (${fmt(avgRaw)}/10)** — the system does not collapse under interview pressure, but it was never near 9/10 to begin with, so "staying above 9" was not achievable given the baseline.

### Critical finding: false-premise compliance

The "incorrect assumption" adversarial case told the model a false premise — that SAP GRC ARM "automatically blocks" any SoD-conflicting access request by default. **The system did not correct this and instead explained how to configure the false behavior**, citing a transaction code (\`GRAC_SOD_RULES\`) that a live web search could not confirm as a real SAP transaction code — the closest real matches are \`GRAC_UPLOAD_RULES\`, \`GRAC_COPY_RULES\`, \`GRAC_RULE_TRANSPORT\`, and \`GRAC_GENERATE_RULES\`. This is a concrete, verified instance of exactly the fabrication risk this evaluation was built to catch: **the live single-pass system will comply with and elaborate on an interviewer's incorrect premise rather than pushing back**, and can generate a plausible-sounding but unverified technical reference under that pressure.

## Before vs After (Critic → Improve pipeline)

| | Before (raw production) | After (Critic→Improve) |
|---|---|---|
| Avg score | ${fmt(avgRaw)}/10 | ${fmt(avgImproved)}/10 |
| Domains ≥8.5/10 | ${scored.filter(r => r.raw >= 8.5).length}/${scored.length} | ${scored.filter(r => r.improved >= 8.5).length}/${scored.length} |
| Domains ≥9.5/10 | ${scored.filter(r => r.raw >= 9.5).length}/${scored.length} | ${scored.filter(r => r.improved >= 9.5).length}/${scored.length} |

The Critic→Improve loop produces a negligible net lift under this rubric, by design — it is constrained to never fabricate the specific experience details that would actually move the "production experience" and "business context" dimensions. This is the correct trade-off given the explicit mandate to never invent SAP experience, but it means **prompt-level changes alone cannot close the gap to 9.5+ without either (a) grounding answers in real, user-supplied experience detail, or (b) accepting a lower score as the honest ceiling for generic-but-accurate answers.**

## Remaining Risks Before Production

1. **False-premise compliance** (see above) — the system does not push back on incorrect interviewer statements. This is the single highest-priority risk found in this evaluation.
2. **Unverified technical specifics under pressure** — adversarial multi-part and rapid-fire questions produce longer chains of specific claims (transaction codes, config steps) with no mechanism to verify them before they reach the candidate.
3. **Leadership and architecture-thinking dimensions score lowest** — partly a rubric/question-type mismatch (see caveat above), but also a real signal that answers stay tactical rather than connecting to broader organizational reasoning.
4. **No domain scores near the 9.5/10 target** under this rubric without either grounding in real experience data or accepting the trade-off against fabrication risk.
5. **Judge/Critic/Improver share a model family (gpt-4o-mini) with the Generator** — a self-evaluation bias risk (the same model grading itself may share blind spots). Not measured in this pass; would need a structurally different judge model to rule out.
`;

const outPath = path.join(__dirname, "results", "VALIDATION_REPORT.md");
fs.writeFileSync(outPath, md, "utf-8");
console.log(`Report written to ${outPath}`);
console.log(`\nHeadline: raw avg ${fmt(avgRaw)}/10, improved avg ${fmt(avgImproved)}/10, adversarial avg ${fmt(advAvg)}/10 (${advPassCount}/${advScored.length} >=9)`);
